export const slugify = (value: string) =>
  value
    .toLowerCase()
    .normalize('NFD')
    .replace(/[\u0300-\u036f]/g, '')
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/^-|-$/g, '');
export function seedToVariant(seed: VehicleSeed): VehicleVariant {
  const source: Source = {
    name: seed.sourceName,
    url: seed.sourceUrl,
    checkedOn: seed.checked ? '2026-10-03' : null,
    status: 'primary-reference',
    note: seed.checked
      ? 'Core reference checked; see specification context for market and measurement differences.'
      : 'Source supplied for review; this record is not exhaustively verified.',
  };
  return {
    id: seed.id,
    generationId: `${seed.brand}-${slugify(seed.model)}-${slugify(seed.generation)}`,
    name: seed.variant,
    slug: slugify(seed.variant),
    year: seed.year,
    bodyStyle: seed.body,
    category: seed.category,
    powertrain: seed.fuel,
    drivetrain: seed.drive,
    transmission: seed.transmission,
    seats: seed.seats,
    doors: seed.doors,
    engine: {
      configuration: seed.engine,
      displacementCc: seed.cc,
      layout: seed.layout,
      aspiration: seed.aspiration,
    },
    performance: {
      powerKw: seed.kw,
      torqueNm: seed.torque,
      zeroTo100: seed.acceleration,
      topSpeedKmh: seed.speed,
    },
    dimensions: { weightKg: seed.weight, weightStandard: seed.weightStandard, ...seed.dimensions },
    battery: seed.battery,
    tags: seed.tags,
    nicknames: [seed.generation, seed.engine, seed.tags.includes('jdm') ? 'Japanese' : ''],
    overview: seed.description,
    engineering: seed.engineering,
    legacy:
      legacyStories[seed.id] ??
      'Explore this record beside other machines from its model family and era. Read its primary reference for historical context.',
    source,
    specificationNote: seed.note,
    mediaId: seed.id,
  };
}
